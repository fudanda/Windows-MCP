export function errorMessage(language: Language, error: unknown): string {
  const code =
    typeof error === "object" && error !== null && "code" in error
      ? String(error.code)
      : "";
  return (
    errors[code]?.[language === "en" ? 1 : 0] ??
    (language === "en"
      ? "Operation failed. Please try again."
      : "操作失败，请重试。")
  );
}
